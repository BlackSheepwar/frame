/**
 * @file svc_key_logic.h
 * @brief 服务层：按键消抖、单击/长按判定，事件打包后投进队列
 * @author Ricardo
 * @date 2026-10-23
 *
 * @note 时间由调用方按毫秒喂进来，本层不认识扫描周期。
 *
 *       一次完整的按键会产出这样一串事件：
 *
 *         按一下：按下 ──> DOWN ──(松开)──> CLICK
 *
 *         按住：  按下 ──> DOWN ──(满 long_ms)──> LONG
 *                            ──(每 repeat_ms)──> REPEAT …
 *                            ──(松开)──> LONG_UP
 *
 *       本层的职责到"把数据塞进队列"为止：
 *         - 不阻塞、不等待、不睡眠；
 *         - 不提供取事件的函数，消费者（Task_Key_Cmd）自己
 *           osMessageQueueGet(KEY_EVT_QHandle, ...) 去睡、去唤醒。
 */

#ifndef __SVC_KEY_LOGIC_H__
#define __SVC_KEY_LOGIC_H__

/*==============================================================================
 * 头文件包含
 *============================================================================*/
// 固定包含
#include <stdint.h>
// 功能包含
#include"dev_key.h"            /* dev_key_t：事件按设备句柄回传 */

/*==============================================================================
 * 类型定义
 *============================================================================*/
/**
 * @brief 按键事件类型
 * @note 顺序有意义：NONE 必须为 0，其余单调递增（命令表按值比较）。
 */
typedef enum {
    KEY_EVENT_NONE      = 0,            /* 无事件 */
    KEY_EVENT_DOWN      = 1,            /* 单点按下 */
    KEY_EVENT_CLICK     = 2,            /* 单点释放 */
    KEY_EVENT_LONG      = 3,            /* 长按触发 */
    KEY_EVENT_REPEAT    = 4,            /* 长按连发 */
    KEY_EVENT_LONG_UP   = 5,            /* 长按释放 */
} key_event_t;

/**
 * @brief 一条按键事件：消抖任务产出的唯一数据
 * @note 队列里存的就是它，换投递方式时结构体不用动。
 *       key 是设备句柄本身，不是编号：同一颗键在整个工程里只有
 *       一个地址，命令表直接按地址认，不存在"编号配错句柄"的可能。
 *       代价是这条消息不再是纯值——不能直接打印、不能落盘、不能跨核，
 *       要加 UART 日志时得另配一张"句柄 → 名字"的表。
 */
typedef struct {
    const dev_key_t *key;               /* 哪个键：Device 层句柄，命令表按它匹配 */
    key_event_t      event;             /* 发生了什么 */
} key_event_msg_t;

/*==============================================================================
 * 函数声明
 *============================================================================*/
/**
 * @brief 初始化：以上电电平作为初始稳定态
 * @note 必须早于 Svc_Key_Logic_Tick() 调用；
 *       在 osKernelStart() 之前调用也安全（只有状态清零，不碰调度器）。
 */
void Svc_Key_Logic_Init(void);

/**
 * @brief 周期处理：采样、消抖、事件判定，事件投递给下游
 * @param elapsed_ms 距上次调用的真实毫秒数，0 会被当成 1
 * @note 本身绝不阻塞：投递用的是零超时的 osMessageQueuePut，
 *       队列满就丢一条并计数，不会让扫描线程停在这里。
 */
void Svc_Key_Logic_Tick(uint16_t elapsed_ms);

#endif /* __SVC_KEY_LOGIC_H__ */
