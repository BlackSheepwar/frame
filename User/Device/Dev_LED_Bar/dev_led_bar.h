/**
 * @file dev_led_bar.h
 * @brief 设备层：一串灯 = 一组 BSP 引脚句柄
 * @author Ricardo
 * @date 2026-10-23
 *
 * @note 只回答"这个设备能做什么"，不回答"什么时候做"。
 *       上层统一用 Dev_Led_Bar_Set(n) 控制，不管底层是 8 个 GPIO、
 *       一颗 WS2812、还是一块 I2C 的 LED 驱动芯片。
 */

#ifndef __Dev_Led_Bar_H__
#define __Dev_Led_Bar_H__

/*==============================================================================
 * 头文件包含
 *============================================================================*/
// 固定包含
#include <stdint.h>

/*==============================================================================
 * 类型定义
 *============================================================================*/
/**
 * @brief 灯带设备句柄（不透明类型，成员定义在 dev_led_bar.c）
 */
typedef struct dev_led_bar dev_led_bar_t;

/*==============================================================================
 * 外部声明
 *============================================================================*/
/**
 * @brief 8 颗 LED 进度条（PA0~PA7，高电平点亮）
 */
extern const dev_led_bar_t dev_led_bar_0;

/*==============================================================================
 * 函数声明
 *============================================================================*/
/**
 * @brief 点亮前 lit 颗灯，其余熄灭
 * @param bar 灯带设备句柄
 * @param lit 点亮颗数，超出范围自动夹紧到 [0, Dev_LED_Bar_Count(bar)]
 */
void Dev_LED_Bar_Set(const dev_led_bar_t *bar, uint8_t lit);

/**
 * @brief 查询灯带灯珠数量
 * @param bar 灯带设备句柄，不能为 NULL
 * @retval 非 0: 该灯带的灯珠数量
 * @retval 0: bar 为 NULL，或灯带本身没有配置灯珠
 * @note 句柄是不透明类型，成员只在 dev_led_bar.c 里可见，上层要用数量
 *       必须走本函数，不要试图访问 bar->count。
 */
uint8_t Dev_LED_Bar_Count(const dev_led_bar_t *bar);

#endif /* __Dev_Led_Bar_H__ */
