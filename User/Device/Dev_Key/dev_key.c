/**
 * @file dev_key.c
 * @brief 设备层实现：按键 = BSP 引脚句柄 + 极性
 * @author Ricardo
 * @date 2026-10-23
 *
 * @note 一台按键只做一件事：把电平换算成"按下 / 松开"。
 *       不延时、不记状态、不去抖——那些是 Service 层的事。
 */

/*==============================================================================
 * 头文件包含
 *============================================================================*/
// 固定包含
#include <stddef.h>
#include "dev_key.h"
#include "bsp_gpio.h"

/*==============================================================================
 * 类型定义
 *============================================================================*/
/**
 * @brief 按键设备句柄（一台按键一份，可多个并存）
 */
 struct dev_key{
    const bsp_gpio_t *gpio;             /* 引脚句柄（BSP 层资源） */
    uint8_t           polarity;         /* 0: 低电平表示按下，1: 高电平表示按下 */
};

/*==============================================================================
 * 设备句柄
 *============================================================================*/
const dev_key_t dev_key_dec = { .gpio= &bsp_gpio_pb1,  .polarity = 0u};
const dev_key_t dev_key_inc = { .gpio= &bsp_gpio_pb11, .polarity = 0u};
const dev_key_t dev_key_led = { .gpio= &bsp_gpio_pb10, .polarity = 0u};

/*==============================================================================
 * 接口实现
 *============================================================================*/
/**
 * @brief 读取按键当前是否按下
 * @param key 按键设备句柄
 * @retval 1: 按下
 * @retval 0: 松开
 */
uint8_t Dev_Key_Read(const dev_key_t *key)
{
    if ((key == NULL) || (key->gpio == NULL)) {
        return 0u;
    }

    if (key->polarity != 1u) {
        return (BSP_GPIO_Read(key->gpio) == 0u) ? 1u : 0u;
    }

    return BSP_GPIO_Read(key->gpio);
}
