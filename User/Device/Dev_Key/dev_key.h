/**
 * @file dev_key.h
 * @brief 设备层：一个按键 = 一个 BSP 引脚句柄 + 极性
 * @author 李嘉图
 * @date 2026-10-23
 *
 * @note 只回答"这个按键现在按着没有"，不回答"按多久算长按"。
 *       消抖、长按、连发属于业务逻辑，放在 Service 层。
 */

#ifndef __Dev_Key_H__
#define __Dev_Key_H__

/*==============================================================================
 * 头文件包含
 *============================================================================*/
// 固定包含
#include <stdint.h>

/*==============================================================================
 * 类型定义
 *============================================================================*/
/**
 * @brief 按键设备句柄（不透明类型，成员定义在 dev_key.c）
 */
typedef struct dev_key dev_key_t;

/*==============================================================================
 * 外部声明
 *============================================================================*/
extern const dev_key_t dev_key_inc;
extern const dev_key_t dev_key_dec;
extern const dev_key_t dev_key_led;

/*==============================================================================
 * 函数声明
 *============================================================================*/
/**
 * @brief 读取按键当前是否按下
 * @param key 按键设备句柄
 * @retval 1: 按下
 * @retval 0: 松开
 */
uint8_t Dev_Key_Read(const dev_key_t *key);

#endif /* __Dev_Key_H__ */
