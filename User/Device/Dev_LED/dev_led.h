/**
 * @file dev_led.h
 * @brief 设备层接口：LED = BSP 引脚句柄 + 极性
 * @author 李嘉图
 * @date 2026-10-25
 *
 * @note 本文件不含端口号、引脚号、模式、上下拉——那些在 BSP 层。
 *       这里只记"那个引脚属于这个 LED、什么极性可以点亮 LED"。
 */

#ifndef __Dev_LED_H__
#define __Dev_LED_H__

/*==============================================================================
 * 头文件包含
 *============================================================================*/
// 固定包含
#include <stdint.h>

/*==============================================================================
 * 类型定义
 *============================================================================*/
/**
 * @brief LED 亮灭状态
 * @note 0 定为"灭"：状态量被清零后天然是灭灯，属安全默认值。
 *       枚举常量是编译期常量，本类型不分配任何存储，零 RAM 开销。
 */
typedef enum {
    LED_OFF = 0,                        /* LED 灭 */
    LED_ON  = 1,                        /* LED 亮 */
} dev_led_state_t;

/**
 * @brief LED 设备句柄（不透明类型，成员定义在 dev_led.c）
 */
typedef struct dev_led dev_led_t;

/*==============================================================================
 * 外部声明：本板只有一个 LED
 *============================================================================*/
/**
 * @brief 板载 LED 实例（PC13，低电平点亮）
 * @note const 句柄编译期进 .rodata，不占 RAM。
 */
extern const dev_led_t dev_led_1;

/*==============================================================================
 * 函数声明
 *============================================================================*/
/**
 * @brief 按状态点亮或熄灭 LED
 * @param led   LED 设备句柄，不可为 NULL
 * @param state 目标状态：LED_ON 点亮，LED_OFF 熄灭
 * @retval 1: 已把电平写入引脚
 * @retval 0: led 或 led->gpio 为空指针，或 state 不是已知状态（此时不动作）
 * @note polarity 记的是"点亮电平"（0=低电平点亮），熄灭时取它的反。
 */
uint8_t Dev_LED_Write(const dev_led_t *led, dev_led_state_t state);

/**
 * @brief 翻转LED状态
 * @param led   LED 设备句柄，不可为 NULL
 * @retval 1: 已把电平写入引脚
 * @retval 0: led 或 led->gpio 为空指针（此时不动作）
 */
uint8_t Dev_LED_Toggle(const dev_led_t *led);

#endif /* __Dev_LED_H__ */
